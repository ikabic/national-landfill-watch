CREATE EXTENSION IF NOT EXISTS postgis;

-- Table: public.landfills

-- DROP TABLE IF EXISTS public.landfills;

CREATE TABLE IF NOT EXISTS public.landfills
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_name text COLLATE pg_catalog."default",
    status text COLLATE pg_catalog."default",
    start_year integer,
    life_years integer,
    area_m2 double precision,
    volume_m3 double precision,
    total_mass_ton double precision,
    annual_msw_m3 double precision,
    annual_ch4_tonnes double precision,
    annual_co2e_tonnes double precision,
    geojson jsonb,
    center_lat double precision,
    center_lon double precision,
    geom geography(Point,4326),
    influence_radius double precision,
    center_x_px double precision,
    center_y_px double precision,
    width_px double precision,
    height_px double precision,
    segmentation jsonb
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.landfills
    OWNER to postgres;
-- Index: idx_landfills_geom

-- DROP INDEX IF EXISTS public.idx_landfills_geom;

CREATE INDEX IF NOT EXISTS idx_landfills_geom
    ON public.landfills USING gist
    (geom)
    WITH (fillfactor=90, buffering=auto)
    TABLESPACE pg_default;

